import path from 'node:path';
import { launch } from '../../../tools/capture.mjs';
import { startServer } from '../../../tools/server.mjs';
const project = path.basename(path.resolve(import.meta.dirname, '..'));
const server = await startServer();
const browser = await launch();
const page = await browser.newPage();
await page.goto(server.url(project) + 'dev/bench.html');
await page.waitForFunction(() => window.DONE, { timeout: 280000 });
console.log(await page.evaluate(() => document.getElementById('o').textContent));
await browser.close(); server.close(); process.exit(0);
